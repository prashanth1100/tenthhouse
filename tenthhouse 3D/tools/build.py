def src(stem: str, v: str) -> str:
    return f"{IMG_BASE}{stem}-{v}.jpg"

def dims(v: str) -> tuple[int, int]:
    w, h = v.split("x"); return int(w), int(h)

def full_url(img_id: str) -> str:
    stem, variants, *_ = IMAGES[img_id]
    return src(stem, variants[-1])

def img(img_id: str, sizes: str, cls: str = "", eager: bool = False, alt: str | None = None) -> str:
    stem, variants, alt_text, *_ = IMAGES[img_id]
    srcset = ", ".join(f"{src(stem, v)} {dims(v)[0]}w" for v in sorted(variants, key=lambda v: dims(v)[0]))
    fallback = sorted(variants, key=lambda v: dims(v)[0])[min(1, len(variants) - 1)]
    w, h = dims(variants[-1])
    attrs = [f'src="{src(stem, fallback)}"', f'srcset="{srcset}"', f'sizes="{sizes}"',
             f'width="{w}"', f'height="{h}"', f'alt="{e(alt if alt is not None else alt_text)}"', 'decoding="async"']
    attrs.append('loading="eager" fetchpriority="high"' if eager else 'loading="lazy"')
    if cls: attrs.append(f'class="{cls}"')
    tag = "<img " + " ".join(attrs) + ">"
    # When photos are served locally and WebP copies exist (tools/fetch-images.sh), offer WebP first.
    if not IMG_BASE.startswith("http"):
        webp = [(src(stem, v).replace(".jpg", ".webp"), dims(v)[0]) for v in sorted(variants, key=lambda v: dims(v)[0])]
        if all((ROOT / u).exists() for u, _ in webp):
            ss = ", ".join(f"{u} {w}w" for u, w in webp)
            return f'<picture><source type="image/webp" srcset="{ss}" sizes="{sizes}">{tag}</picture>'
    return tag

